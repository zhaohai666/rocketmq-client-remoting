#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Prepare the mingw-w64 header tree (used by win_syntax_check.sh).
#
# Why this is needed: this host has no Windows cross toolchain and cannot install one (brew's mingw-w64
# recipe ships source only; building requires sandbox-exec, which the current environment forbids via
# sandbox_apply). Still, the **real Windows headers** are obtainable — mingw-w64-headers in the
# mingw-w64 source is the authoritative declaration set for winsock2.h / windows.h. With it a real
# semantic check (`-fsyntax-only`) of Windows code paths becomes possible — the strongest validation available.
#
# The header tree is "half-built": `_mingw.h` is normally generated by configure, so @...@ placeholders must be substituted.
# Only two placeholders exist: DEFAULT_MSVCRT_VERSION / DEFAULT_WIN32_WINNT.
#
# Usage: bash win_prepare_headers.sh [destination directory]     default /tmp/rmq_mingw_hdr
# ---------------------------------------------------------------------------
set -euo pipefail

DEST="${1:-/tmp/rmq_mingw_hdr}"
HDR="$DEST/mingw-w64-headers/include"
CRT="$DEST/mingw-w64-headers/crt"

if [ -f "$HDR/winsock2.h" ] && [ -f "$CRT/_mingw.h" ]; then
    echo "Header tree already ready: $DEST"
    exit 0
fi

# Locate a mingw-w64 source tarball: prefer the Homebrew download cache, then fall back to fetching from the network.
TARBALL=""
for cand in "$HOME"/Library/Caches/Homebrew/downloads/*mingw-w64*.tar.bz2; do
    [ -f "$cand" ] && TARBALL="$cand" && break
done

if [ -z "$TARBALL" ]; then
    echo "No mingw-w64 source tarball found in the local cache."
    echo "Run this first:  brew fetch mingw-w64"
    echo "(brew fetch only downloads without building, so no sandbox is needed)"
    exit 1
fi

echo "Using source tarball: $TARBALL"
rm -rf "$DEST"
mkdir -p "$DEST"
tar xjf "$TARBALL" -C "$DEST" --strip-components=1 mingw-w64-v*/mingw-w64-headers

if [ ! -f "$HDR/winsock2.h" ]; then
    echo "$HDR/winsock2.h not found after unpacking — the package layout may have changed." >&2
    exit 1
fi

# Generate _mingw.h, which configure would normally produce
if [ -f "$CRT/_mingw.h.in" ]; then
    sed -e 's/@DEFAULT_MSVCRT_VERSION@/0x0601/' \
        -e 's/@DEFAULT_WIN32_WINNT@/0x0601/' \
        "$CRT/_mingw.h.in" > "$CRT/_mingw.h"
fi

# Caution: `grep -c` returns non-zero on 0 matches; combined with set -e/pipefail that would abort the script,
# so `|| true` is required here to catch it.
left=$(grep -c '@[A-Za-z_0-9]*@' "$CRT/_mingw.h" 2>/dev/null | head -1 || true)
[ -z "$left" ] && left=0
if [ "$left" != "0" ]; then
    echo "Warning: _mingw.h still has $left unreplaced placeholders; this may affect check results." >&2
fi

echo "Header tree generated:"
echo "  include: $HDR"
echo "  crt    : $CRT"
